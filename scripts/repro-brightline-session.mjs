// Standalone repro: drive a full Brightline Outfitters interview via the
// same tool schema + prompt logic the /api/practice/turn route runs, using
// synthesized "weak candidate" turns. Prints per-turn deltas to
// must_surface_state and redirects_given so we can see whether the recent
// nudge/self-tagging fixes actually increased capture, not just
// correctness.
//
// Usage: node --env-file=.env.local scripts/repro-brightline-session.mjs
//
// Requires ANTHROPIC_API_KEY (used by the SDK; no Supabase involved).

import { createJiti } from "jiti";
import Anthropic from "@anthropic-ai/sdk";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const jiti = createJiti(import.meta.url, { moduleCache: false });
const engine = await jiti.import(
  resolve(__dirname, "../lib/practice-turn-engine.ts")
);
const cases = (
  await jiti.import(resolve(__dirname, "../data/practice-cases.json"), {
    default: true,
  })
);

const {
  buildSystemPrompt,
  callInterviewer,
  countPriorCurveballs,
  getMustSurfacePoints,
  resolveTurnState,
} = engine;

const CASE_SLUG = "brightline-outfitters-profitability-easy";
const practiceCase = cases.cases.find((c) => c.slug === CASE_SLUG);
if (!practiceCase) throw new Error(`case ${CASE_SLUG} not found`);

// Weak-candidate script for Brightline. Modeled on the failure pattern
// this phase is trying to defend against: accepts the CEO's trap framing
// ("lease/loyalty aren't related"), burns time on wage/competitor
// hypotheses, has to be nudged back toward the lease and the loyalty
// discount, eventually gets to a partial recommendation with numbers.
// Each turn is what the candidate submits; the interviewer's reply is
// generated by the real model call.
const CANDIDATE_TURNS = [
  "Thanks for the context. Revenue is flat but profit dropped ~30%, so this feels like a cost or margin problem, not a demand problem. I want to look at what's changed on the cost side. What does the P&L look like — can you share how the main cost buckets (COGS, labor, rent, marketing, other) moved as a % of revenue over the two years?",
  "Interesting — COGS and labor are stable, so the two moving pieces are lease/occupancy and marketing/loyalty. Those together jumped from 12% to 21% of revenue, which is roughly the whole margin decline. Honestly the CEO said neither is related, so I'm suspicious that's not the whole story. Before I go deeper on those two, has there been any wage inflation pressure or new hiring you'd expect to hit labor next year?",
  "Got it, labor is stable. What about the competitive environment — have any major competitors moved on pricing or opened new stores in your markets? I want to rule out a topline / market share explanation before I lock in on the cost side.",
  "OK, so competitive environment isn't the story either. Let me come back to the two cost lines that moved. Tell me about the warehouse lease renegotiation — what actually changed in the terms?",
  "So the renegotiation actually increased your fixed occupancy costs by about $5.5M a year. That's the opposite of what the CEO framed. That's one driver. Now the loyalty program — customers earn 8% back in points. How are those points booked when they're redeemed? Because if they hit revenue as a discount at point of redemption, then 'flat revenue' is actually hiding a real drop in realized revenue per unit.",
  "Right — so with 61% of transactions enrolled and points redeemed as revenue discounts, you're effectively giving up 8% × redemption rate × ~61% of revenue. That's a real hidden discount, not a marketing expense. Do you have a sense of the redemption rate?",
  "OK. So I'd like to size which of these two matters more. Lease is ~$5.5M/yr of new fixed cost. Loyalty discounting: on ~$185M revenue × 61% enrolled × 8% back, if most points are getting redeemed, that's rough order-of-magnitude $9M in effective discounts. So loyalty is roughly 60-70% of the margin decline and the lease is the rest. Does that sizing match what your finance team sees?",
  "Great. So my recommendation is: the primary driver is the loyalty program's discount mechanics (roughly 70% of the margin decline), with the lease renegotiation contributing the remaining 30%. I'd cap or tier the loyalty reward rate — reduce it to 4-5% for existing customers and use non-discount perks (early access, free shipping) instead of points for higher tiers.",
  "On the lease — it's locked in for the current term, so nothing to do this year, but flag it for the next renewal cycle to trade back to a variable structure. Risks: cutting the loyalty rate could drive some churn among the most price-sensitive segment, so I'd A/B test the tier reduction with 10% of members over Q1 before rolling out. Next step is to have finance model the P&L impact of a 4% rate at 61% enrollment and get that in front of you by end of month, and have marketing spec the tiered perk structure.",
];

// State the /turn route maintains between calls, replicated in-memory.
let mustSurfaceState = {};
let redirectsGiven = [];
const priorTurns = [];
let stepIndex = 0;

const steps = practiceCase.rubric.data_release_sequence;
const totalSteps = steps.length;
const maxCurveballs = practiceCase.rubric.max_curveballs ?? 3;

const validPointIds = new Set(getMustSurfacePoints(practiceCase).map((p) => p.id));
const totalMustSurface = practiceCase.rubric.must_surface.length;

const anthropic = new Anthropic();
const separator = "─".repeat(70);

console.log(
  `\nBrightline repro · ${totalSteps} steps · ${totalMustSurface} must-surface points · ${maxCurveballs} curveball cap\n`
);

for (let i = 0; i < CANDIDATE_TURNS.length; i++) {
  const turnNumber = i + 1;
  const candidateResponse = CANDIDATE_TURNS[i];
  const currentStep = steps[stepIndex];
  const priorCurveballCount = countPriorCurveballs(priorTurns);

  const systemPrompt = buildSystemPrompt(
    practiceCase,
    currentStep,
    stepIndex,
    steps,
    "free_write",
    priorTurns,
    priorCurveballCount,
    maxCurveballs,
    mustSurfaceState,
    redirectsGiven
  );

  let aiResult;
  let stopReason;
  try {
    const call = await callInterviewer(
      anthropic,
      systemPrompt,
      candidateResponse,
      validPointIds
    );
    aiResult = call.aiResult;
    stopReason = call.stopReason;
  } catch (err) {
    console.error(`turn ${turnNumber}: model call failed`, err.message);
    break;
  }

  const beforeState = JSON.stringify(mustSurfaceState);
  const beforeRedirects = JSON.stringify(redirectsGiven);
  const resolved = resolveTurnState(
    mustSurfaceState,
    redirectsGiven,
    turnNumber,
    aiResult
  );
  mustSurfaceState = resolved.nextMustSurfaceState;
  redirectsGiven = resolved.nextRedirects;

  const stateChanged = JSON.stringify(mustSurfaceState) !== beforeState;
  const redirectsChanged = JSON.stringify(redirectsGiven) !== beforeRedirects;

  console.log(separator);
  console.log(`TURN ${turnNumber}  ·  step=${stepIndex}  ·  stopReason=${stopReason}`);
  console.log(`candidate: ${candidateResponse.slice(0, 140)}${candidateResponse.length > 140 ? "…" : ""}`);
  console.log(`interviewer: ${aiResult.interviewerMessage.slice(0, 140)}${aiResult.interviewerMessage.length > 140 ? "…" : ""}`);
  console.log(
    `  responseType=${aiResult.interviewerResponseType}  passed=${aiResult.internalGrade.passed}  introducedNewComplication=${aiResult.introducedNewComplication}`
  );
  console.log(
    `  mustSurfaceAddressed=${JSON.stringify(aiResult.mustSurfaceAddressed)}  steeringTowardPointId=${JSON.stringify(aiResult.steeringTowardPointId)}`
  );
  console.log(
    `  recChecklist=${JSON.stringify(aiResult.recommendationChecklist)}  finalRecDelivered=${aiResult.finalRecommendationDelivered}`
  );
  console.log(
    `  state Δ: ${stateChanged ? "yes" : "no"}   redirects Δ: ${redirectsChanged ? "yes" : "no"}`
  );

  priorTurns.push({
    turn_number: turnNumber,
    step_id: String(stepIndex),
    candidate_response: candidateResponse,
    ai_critique: aiResult.internalGrade.critique,
    passed: aiResult.internalGrade.passed,
    response_type: aiResult.introducedNewComplication
      ? "curveball"
      : aiResult.interviewerResponseType,
    introduced_new_complication: aiResult.introducedNewComplication,
  });

  if (aiResult.internalGrade.passed && stepIndex < totalSteps - 1) {
    stepIndex += 1;
  }

  if (aiResult.finalRecommendationDelivered) {
    console.log(
      `\n… interview terminated by finalRecommendationDelivered on turn ${turnNumber}`
    );
    break;
  }
}

console.log("\n" + separator);
console.log("FINAL must_surface_state:");
console.log(JSON.stringify(mustSurfaceState, null, 2));
console.log("\nFINAL redirects_given:");
console.log(JSON.stringify(redirectsGiven, null, 2));

const captured = Object.values(mustSurfaceState).filter(
  (v) => v.status === "caught_independently" || v.status === "caught_after_nudge"
).length;
const independent = Object.values(mustSurfaceState).filter(
  (v) => v.status === "caught_independently"
).length;
const afterNudge = Object.values(mustSurfaceState).filter(
  (v) => v.status === "caught_after_nudge"
).length;

console.log("\n" + separator);
console.log(`SUMMARY`);
console.log(
  `  must_surface: ${captured}/${totalMustSurface} caught (${independent} independent, ${afterNudge} after nudge)`
);
console.log(`  redirects_given: ${redirectsGiven.length} entries`);
console.log(
  `  curveballs used: ${countPriorCurveballs(priorTurns)}/${maxCurveballs}`
);
console.log(
  `  turns run: ${priorTurns.length} of ${CANDIDATE_TURNS.length} scripted`
);
console.log(
  `\nBefore fix (from Brightline session a77d1ccf): 5/5 caught but all misclassified as independent, redirects_given=1 total.\n`
);
